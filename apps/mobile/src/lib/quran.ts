/**
 * Candidate URLs for one ayah, built from its **global** number (1…6236) —
 * `Ayah.number`, not `numberInSurah`. Nothing is fetched to switch reciter.
 */
export function audioUrlsForAyah(globalAyahNumber: number, reciterId: string): string[] {
  const reciter = RECITERS.find((r) => r.id === reciterId) ?? RECITERS[0];
  return reciter.bitrates.map(
    (b) => `${AUDIO_CDN}/${b}/${reciter.id}/${globalAyahNumber}.mp3`,
  );
}

