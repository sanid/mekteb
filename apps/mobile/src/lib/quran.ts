import { getLocale } from "./i18n";

/**
 * Quran text, fetched straight from alquran.cloud — the same source and the
 * same edition identifiers the web reader uses, so a mosque sees identical
 * text in both products.
 *
 * Audio streams from the islamic.network CDN, the same source as the web
 * reader. Playback itself needs `expo-audio` — a native module, so a client
 * built before it was added has to be rebuilt (AGENTS.md §8).
 *
 * Not routed through `/api/v1`: this is public scripture with no tenant
 * scoping, and going direct keeps it working without a session. Personal
 * bookmarks are the opposite — those go through the API, under RLS.
 */
const BASE = "https://api.alquran.cloud/v1";

export const ARABIC_EDITION = "quran-uthmani";

export type SurahMeta = {
  number: number;
  name: string;
  englishName: string;
  englishNameTranslation: string;
  numberOfAyahs: number;
  revelationType: string;
};

export type Ayah = {
  number: number;
  text: string;
  numberInSurah: number;
  juz: number;
  page: number;
};

export type SurahData = SurahMeta & { ayahs: Ayah[] };

/** Matches `defaultTranslationForLocale` in the web app — keep in step. */
export function translationForLocale(locale: string = getLocale()): string {
  switch (locale) {
    case "de":
      return "de.aburida";
    case "tr":
      return "tr.diyanet";
    case "bs":
      return "bs.mlivo";
    default:
      return "en.sahih";
  }
}

/**
 * The surah list is fixed scripture metadata — it never changes, so it is
 * fetched once per app run and kept.
 */
let surahListCache: SurahMeta[] | null = null;

export async function fetchSurahList(): Promise<SurahMeta[]> {
  if (surahListCache) return surahListCache;
  const res = await fetch(`${BASE}/surah`);
  if (!res.ok) throw new Error("surah_list_failed");
  const json = (await res.json()) as { data: SurahMeta[] };
  surahListCache = json.data;
  return json.data;
}

const surahCache = new Map<string, { arabic: SurahData; translation: SurahData }>();

export async function fetchSurah(
  number: number,
  translationEdition = translationForLocale(),
): Promise<{ arabic: SurahData; translation: SurahData }> {
  const key = `${number}:${translationEdition}`;
  const hit = surahCache.get(key);
  if (hit) return hit;

  const editions = [ARABIC_EDITION, translationEdition].join(",");
  const res = await fetch(`${BASE}/surah/${number}/editions/${editions}`);
  if (!res.ok) throw new Error("surah_failed");
  const json = (await res.json()) as { data: SurahData[] };

  const [arabic, translation] = json.data;
  const value = { arabic, translation };
  surahCache.set(key, value);
  return value;
}

